    private void cargarConsultas() {
        ConexionConsulta CCO = new ConexionConsulta();
        List<Object[]> consultas = CCO.obtenerConsultasPorCliente(IdCliente);

        DefaultTableModel modelo = (DefaultTableModel) Tabla.getModel();
        modelo.setRowCount(0);

        if (consultas.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this,"Aún no tienes consultas registradas.","Sin consultas",javax.swing.JOptionPane.INFORMATION_MESSAGE);
            return;
        }

        for (Object[] fila : consultas) {
            modelo.addRow(fila);
        }
    }


