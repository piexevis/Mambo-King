    private void IniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IniciarActionPerformed
        String fecha = new SimpleDateFormat("dd/MM/yyyy").format(Fecha.getValue());
        String hora = new SimpleDateFormat("HH:mm").format(Hora.getValue());
        String medico = (String) Medico.getSelectedItem();
        String tipo = (String) Tipo.getSelectedItem();
        //Validacion
        if (Fecha.getValue() == null || Hora.getValue() == null) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar una fecha y una hora.", "Campo incompleto", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (tipo == null || tipo.equals("Seleccionar") || medico == null || medico.equals("Seleccione una especialidad primero")) {
            JOptionPane.showMessageDialog(this, "Debe seleccionar un médico y un tipo de consulta.", "Campo incompleto", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        //Validacion de Dates
        Date fechaSeleccionada = (Date) Fecha.getValue();
        Date horaSeleccionada = (Date) Hora.getValue();
        if (esFechaAnterior(fechaSeleccionada)) {
            JOptionPane.showMessageDialog(this, "No se puede registrar una fecha anterior a hoy.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (esHoraProhibida(horaSeleccionada)) {
            JOptionPane.showMessageDialog(this, "La hora seleccionada no está permitida.", "Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        Calendar ahora = Calendar.getInstance();
        Calendar fechaCal = Calendar.getInstance();
        fechaCal.setTime(fechaSeleccionada);
        boolean esHoy = fechaCal.get(Calendar.YEAR) == ahora.get(Calendar.YEAR) && fechaCal.get(Calendar.DAY_OF_YEAR) == ahora.get(Calendar.DAY_OF_YEAR);
        if (esHoy) {
            Calendar horaCal = Calendar.getInstance();
            horaCal.setTime(horaSeleccionada);
            int minutosHora = horaCal.get(Calendar.HOUR_OF_DAY) * 60 + horaCal.get(Calendar.MINUTE);
            int minutosAhora = ahora.get(Calendar.HOUR_OF_DAY) * 60 + ahora.get(Calendar.MINUTE);
            if (minutosHora < minutosAhora) {
                JOptionPane.showMessageDialog(this, "No se puede registrar una hora que ya pasó.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }
        
        //Validacion de Costo
        String textoCosto = Costo.getText().trim();
            if (textoCosto.isEmpty()) {
            JOptionPane.showMessageDialog(this, "ERROR: No hizo el cálculo del costo de la consulta.", "Campo incompleto", JOptionPane.WARNING_MESSAGE);
            return;
        }
        int costo;
        try {
            costo = Integer.parseInt(textoCosto);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El costo debe ser un valor numérico válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (costo <= 0) {
            JOptionPane.showMessageDialog(this, "El costo debe ser mayor a 0.", "Error de valor", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        //Validacion de Base de datos
        try {
            ConexionConsulta CCO = new ConexionConsulta();
            CCO.inserar_datos(hora, fecha, medico, tipo, costo, IdCliente);
            JOptionPane.showMessageDialog(this, "Consulta registrada con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
            limpiarCampos();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al guardar en la base de datos: " + e.getMessage(), "Error de Conexión", JOptionPane.ERROR_MESSAGE);
    }
        
    }//GEN-LAST:event_IniciarActionPerformed

