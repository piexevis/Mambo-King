    private static final int[][] RANGOS_PROHIBIDOS = {
        {0, 8 * 60 + 15},      // 00:00 - 08:15
        {12 * 60, 13 * 60}     // 12:00 - 13:00
    };

    private boolean esHoraProhibida(Date fecha) {
        Calendar cal = Calendar.getInstance();
        cal.setTime(fecha);

        int minutosTotales = cal.get(Calendar.HOUR_OF_DAY) * 60 + cal.get(Calendar.MINUTE);

        for (int[] rango : RANGOS_PROHIBIDOS) {
            if (minutosTotales >= rango[0] && minutosTotales <= rango[1]) {
                return true;
            }
        }
        return false;
    }
    private boolean esFechaAnterior(Date fechaSeleccionada) {
        Calendar hoy = Calendar.getInstance();
        hoy.set(Calendar.HOUR_OF_DAY, 0);
        hoy.set(Calendar.MINUTE, 0);
        hoy.set(Calendar.SECOND, 0);
        hoy.set(Calendar.MILLISECOND, 0);

        Calendar fechaCal = Calendar.getInstance();
        fechaCal.setTime(fechaSeleccionada);
        fechaCal.set(Calendar.HOUR_OF_DAY, 0);
        fechaCal.set(Calendar.MINUTE, 0);
        fechaCal.set(Calendar.SECOND, 0);
        fechaCal.set(Calendar.MILLISECOND, 0);

    return fechaCal.before(hoy);
}
