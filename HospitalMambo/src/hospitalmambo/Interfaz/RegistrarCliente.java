    private void IniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IniciarActionPerformed
        String nombre =  (String) Nombre.getText();
        String correo = (String) Correo.getText();
        String Rut2 = (String) Rut.getText();
        String Edad2 = (String) Edad.getText();
        String dv = (String) DV.getSelectedItem();

        try{
        int rut = Integer.parseInt(Rut.getText());
        int edad = Integer.parseInt(Edad.getText());
        //comprobar si estan vacios los campos
        if(nombre.trim().isEmpty() || correo.trim().isEmpty() || Rut2.trim().isEmpty() || Edad2.trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Error: completa Todos los campos","Campo Incompleto",JOptionPane.ERROR_MESSAGE);
            return;
        }
        //Rut
        String rutcompleto = rut+ "-"+dv;
        
        //Creacion de lo otro
        ConexionCliente CC = new ConexionCliente();
        int idCliente = CC.inserar_datos(nombre, correo, rutcompleto, edad);
        if (idCliente == -2) {
            JOptionPane.showMessageDialog(null, "Este Rut ya está registrado","Cliente duplicado", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (idCliente == -1) {
            JOptionPane.showMessageDialog(null, "Error al registrar el cliente","Error de base de datos", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        
        
        dispose(); // cierra Registrarse
        VentanaInicialConsulta VIC = new VentanaInicialConsulta((java.awt.Frame) this.getOwner(), true, idCliente);
        VIC.setVisible(true);

        }catch (Exception e){
            JOptionPane.showMessageDialog(null, "ERROR: Debe de ingresar un numero en Edad y Rut","Campo Erroneo", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_IniciarActionPerformed

