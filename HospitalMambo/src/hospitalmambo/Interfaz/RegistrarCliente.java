    private void limitarRut() {
    ((AbstractDocument) Rut.getDocument()).setDocumentFilter(new DocumentFilter() {
        @Override
        public void insertString(FilterBypass fb, int offset, String string, AttributeSet attr) throws BadLocationException {
            String textoFinal = fb.getDocument().getText(0, fb.getDocument().getLength()) + string;
            if (string.matches("\\d*") && textoFinal.length() <= 8) {
                super.insertString(fb, offset, string, attr);
            }
        }

        @Override
        public void replace(FilterBypass fb, int offset, int length, String text, AttributeSet attrs) throws BadLocationException {
            String textoFinal = fb.getDocument().getText(0, fb.getDocument().getLength()).substring(0, offset)
                    + text
                    + fb.getDocument().getText(0, fb.getDocument().getLength()).substring(offset + length);
            if (text.matches("\\d*") && textoFinal.length() <= 8) {
                super.replace(fb, offset, length, text, attrs);
            }
        }
    });
}

